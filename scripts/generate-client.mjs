import { readFile, writeFile, mkdir } from "node:fs/promises";
import { resolve } from "node:path";
const root = resolve(import.meta.dirname, ".."),
  document = JSON.parse(
    await readFile(resolve(root, "docs/openapi.json"), "utf8"),
  );
const type = (schema = {}) => {
  if (schema.$ref)
    return type(document.components.schemas[schema.$ref.split("/").at(-1)]);
  if (schema.enum) return schema.enum.map(JSON.stringify).join(" | ");
  if (schema.const !== undefined) return JSON.stringify(schema.const);
  if (schema.anyOf || schema.oneOf)
    return `(${(schema.anyOf ?? schema.oneOf).map(type).join(" | ")})`;
  let result = "unknown";
  if (schema.type === "array") result = `Array<${type(schema.items)}>`;
  else if (schema.type === "string")
    result = schema.format === "binary" ? "Blob" : "string";
  else if (["number", "integer"].includes(schema.type)) result = "number";
  else if (schema.type === "boolean") result = "boolean";
  else if (schema.type === "null") result = "null";
  else if (schema.type === "object" || schema.properties) {
    const entries = Object.entries(schema.properties ?? {}).map(
      ([key, value]) =>
        `${JSON.stringify(key)}${schema.required?.includes(key) ? "" : "?"}: ${type(value)}`,
    );
    result = `{ ${entries.join("; ")} }`;
    if (schema.additionalProperties)
      result += ` & Record<string, ${schema.additionalProperties === true ? "unknown" : type(schema.additionalProperties)}>`;
  }
  return schema.nullable ? `(${result} | null)` : result;
};
const routes = {},
  entries = [];
for (const [path, item] of Object.entries(document.paths))
  for (const [method, op] of Object.entries(item)) {
    if (!op.operationId) continue;
    const body = op.requestBody?.content?.["application/json"]?.schema;
    const params = (op.parameters ?? [])
      .filter((p) => p.in === "path")
      .map((p) => `${JSON.stringify(p.name)}: string`)
      .join("; ");
    const query = (op.parameters ?? [])
      .filter((p) => p.in === "query")
      .map((p) => `${JSON.stringify(p.name)}?: string | number`)
      .join("; ");
    const response = op.responses?.[200]?.content;
    const output =
      path === "/api/state" || path === "/api/commands"
        ? "{ state: DemoState; role?: string; userId?: string | null }"
        : type(
            response?.["application/json"]?.schema ??
              response?.["application/octet-stream"]?.schema,
          );
    entries.push(
      `${JSON.stringify(op.operationId)}: { body: ${path === "/api/uploads" ? "FormData" : body ? type(body) : "undefined"}; params: { ${params} }; query: { ${query} }; response: ${output} }`,
    );
    routes[op.operationId] = {
      path,
      method: method.toUpperCase(),
      binary: !!response?.["application/octet-stream"],
    };
  }
const source = `// Generated by pnpm generate:client. Edit API schemas, then regenerate.\nimport { api, apiBase, currentArea, ApiError } from "../api";\nimport type { DemoState } from "../model";\nexport interface Operations {\n${entries.join(";\n")}\n}\nconst routes = ${JSON.stringify(routes, null, 2)} as const;\nexport async function request<K extends keyof Operations>(operation: K, options: { params: Operations[K]["params"]; query?: Operations[K]["query"]; area?: string; key?: string } & (undefined extends Operations[K]["body"] ? { body?: Operations[K]["body"] } : { body: Operations[K]["body"] })): Promise<Operations[K]["response"]> {\n const route = routes[operation];\n let path: string = route.path;\n for (const [key,value] of Object.entries(options.params)) path=path.replace("{"+key+"}",encodeURIComponent(String(value)));\n const query = new URLSearchParams();\n for(const [key,value] of Object.entries(options.query ?? {})) if(value !== undefined) query.set(key,String(value));\n if(query.size) path += "?"+query.toString();\n if(route.binary) { const response=await fetch(apiBase+path.replace(/^\\/api/,""),{credentials:"include",cache:"no-store"}); if(!response.ok) throw new ApiError("ファイルを取得できません",response.status,"download_failed"); return await response.blob() as Operations[K]["response"]; }\n return api<Operations[K]["response"]>(path.replace(/^\\/api/,""),options.body,route.method,options.area ?? currentArea(),options.key);\n}\n`;
await mkdir(resolve(root, "apps/member/src/generated"), { recursive: true });
await writeFile(
  resolve(root, "apps/member/src/generated/api-client.ts"),
  source,
);
console.log(`Generated ${entries.length} operations`);
